/* | Feature                        | Example                                               |
| ------------------------------ | ----------------------------------------------------- |
| **Static Typing**              | `let name: string = "Sandip";`                        |
| **Type Inference**             | `let age = 25;`                                       |
| **Interfaces**                 | `interface User { name: string }`                     |
| **Type Aliases**               | `type ID = string | number;`                         |
| **Enums**                      | `enum Role { Admin, User }`                           |
| **Generics**                   | `function get<T>(value: T): T {}`                     |
| **Union Types**                | `string | number`                                    |
| **Intersection Types**         | `A & B`                                               |
| **Literal Types**              | `"success" | "failed"`                               |
| **Tuples**                     | `[string, number]`                                    |
| **Function Overloading**       | Multiple function signatures                          |
| **Access Modifiers**           | `public`, `private`, `protected`                      |
| **Readonly**                   | `readonly id: number;`                                |
| **Optional Properties**        | `age?: number`                                        |
| **Optional Parameters**        | `function f(name?: string)`                           |
| **Type Assertions**            | `value as string`                                     |
| **Type Guards**                | `typeof`, `instanceof`, custom guards                 |
| **Abstract Classes**           | `abstract class Animal {}`                            |
| **Declaration Files**          | `.d.ts`                                               |
| **Namespaces**                 | `namespace Demo {}`                                   |
| **Utility Types**              | `Partial`, `Pick`, `Omit`, `Record`, `Required`, etc. |
| **Special Types**              | `any`, `unknown`, `never`, `void`                     |
| **Compile-time Type Checking** | Errors before JS is generated                         | */



